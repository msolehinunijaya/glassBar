//! Quick notes: text + pasted images (stored as files), color, pin,
//! optional "temporary" expiry, and a 7-day trash.
use crate::db::{now_ms, Db};
use base64::Engine;
use rusqlite::params;
use serde::Serialize;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU32, Ordering};
use tauri::{AppHandle, Emitter, Manager, State, WebviewWindow};

const DAY: i64 = 86_400_000;
pub const MAX_IMAGE: usize = 10 * 1024 * 1024;
const TRASH_DAYS: i64 = 7;

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Note {
    pub id: i64, pub text: String, pub color: String, pub pinned: bool,
    pub images: Vec<String>, pub updated_at: i64, pub deleted_at: Option<i64>,
}

/// Temporary mode: an unpinned note untouched for `days` is moved to trash.
pub fn expired(now: i64, updated_at: i64, pinned: bool, days: Option<u32>) -> bool {
    match days {
        Some(d) if d > 0 && !pinned => now - updated_at > d as i64 * DAY,
        _ => false,
    }
}

/// Trashed notes are removed for good after 7 days.
pub fn purge_due(now: i64, deleted_at: i64) -> bool { now - deleted_at >= TRASH_DAYS * DAY }

/// Accept PNG or JPEG up to 10 MB; returns the file extension.
pub fn check_image(bytes: &[u8]) -> Result<&'static str, String> {
    if bytes.len() > MAX_IMAGE { return Err("Image is larger than 10 MB".into()); }
    if bytes.starts_with(b"\x89PNG\r\n\x1a\n") { return Ok("png"); }
    if bytes.starts_with(&[0xff, 0xd8, 0xff]) { return Ok("jpg"); }
    Err("Only PNG or JPEG images can be pasted".into())
}

/// Image names are generated by us; anything else (paths, traversal) is refused.
pub fn safe_name(name: &str) -> bool {
    !name.is_empty()
        && !name.contains("..")
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '.')
}

fn dir() -> PathBuf { crate::data_dir().join("notes") }

fn image_path(name: &str) -> Result<PathBuf, String> {
    if safe_name(name) { Ok(dir().join(name)) } else { Err("bad image name".into()) }
}

const COLS: &str = "id, text, color, pinned, images, updated_at, deleted_at";

fn row(r: &rusqlite::Row) -> rusqlite::Result<Note> {
    let images: String = r.get(4)?;
    Ok(Note {
        id: r.get(0)?, text: r.get(1)?, color: r.get(2)?, pinned: r.get(3)?,
        images: serde_json::from_str(&images).unwrap_or_default(), updated_at: r.get(5)?, deleted_at: r.get(6)?,
    })
}

fn changed(app: &AppHandle) { let _ = app.emit("notes:changed", ()); }

fn images_of(c: &rusqlite::Connection, id: i64) -> Result<Vec<String>, String> {
    let s: String = c.query_row("SELECT images FROM notes WHERE id = ?1", [id], |r| r.get(0)).map_err(|e| e.to_string())?;
    Ok(serde_json::from_str(&s).unwrap_or_default())
}

fn set_images(c: &rusqlite::Connection, id: i64, list: &[String]) -> Result<(), String> {
    c.execute("UPDATE notes SET images = ?2, updated_at = ?3 WHERE id = ?1",
              params![id, serde_json::to_string(list).unwrap(), now_ms()])
        .map(|_| ()).map_err(|e| e.to_string())
}

#[tauri::command]
pub fn notes_list(db: State<Db>, trash: bool) -> Vec<Note> {
    let c = db.0.lock().unwrap();
    let filter = if trash { "deleted_at IS NOT NULL" } else { "deleted_at IS NULL" };
    let mut q = c.prepare(&format!("SELECT {COLS} FROM notes WHERE {filter} ORDER BY pinned DESC, updated_at DESC")).unwrap();
    q.query_map([], row).map(|r| r.filter_map(Result::ok).collect()).unwrap_or_default()
}

#[tauri::command]
pub fn note_create(app: AppHandle) -> Result<Note, String> {
    let n = {
        let db = app.state::<Db>();
        let c = db.0.lock().unwrap();
        c.execute("INSERT INTO notes(updated_at) VALUES(?1)", [now_ms()]).map_err(|e| e.to_string())?;
        c.query_row(&format!("SELECT {COLS} FROM notes WHERE id = ?1"), [c.last_insert_rowid()], row).map_err(|e| e.to_string())?
    };
    changed(&app);
    Ok(n)
}

#[tauri::command]
pub fn note_update(app: AppHandle, id: i64, text: String, color: String, pinned: bool) -> Result<(), String> {
    app.state::<Db>().0.lock().unwrap()
        .execute("UPDATE notes SET text = ?2, color = ?3, pinned = ?4, updated_at = ?5 WHERE id = ?1",
                 params![id, text, color, pinned, now_ms()])
        .map_err(|e| e.to_string())?;
    changed(&app);
    Ok(())
}

#[tauri::command]
pub fn note_delete(app: AppHandle, id: i64) {
    let _ = app.state::<Db>().0.lock().unwrap().execute("UPDATE notes SET deleted_at = ?2 WHERE id = ?1", params![id, now_ms()]);
    changed(&app);
}

#[tauri::command]
pub fn note_restore(app: AppHandle, id: i64) {
    let _ = app.state::<Db>().0.lock().unwrap()
        .execute("UPDATE notes SET deleted_at = NULL, updated_at = ?2 WHERE id = ?1", params![id, now_ms()]);
    changed(&app);
}

static SEQ: AtomicU32 = AtomicU32::new(0);

/// Save a pasted image (base64 or data: URL) and attach it to note `id`.
#[tauri::command]
pub fn note_add_image(app: AppHandle, id: i64, data: String) -> Result<String, String> {
    let b64 = data.split_once(',').map(|(_, d)| d).unwrap_or(&data);
    if b64.len() > MAX_IMAGE / 3 * 4 + 8 { return Err("Image is larger than 10 MB".into()); }
    let bytes = base64::engine::general_purpose::STANDARD.decode(b64).map_err(|_| "Not an image".to_string())?;
    let ext = check_image(&bytes)?;
    let name = format!("{id}-{}-{}.{ext}", now_ms(), SEQ.fetch_add(1, Ordering::Relaxed));
    std::fs::create_dir_all(dir()).map_err(|e| e.to_string())?;
    std::fs::write(image_path(&name)?, &bytes).map_err(|e| e.to_string())?;
    {
        let db = app.state::<Db>();
        let c = db.0.lock().unwrap();
        let mut list = images_of(&c, id)?;
        list.push(name.clone());
        set_images(&c, id, &list)?;
    }
    changed(&app);
    Ok(name)
}

#[tauri::command]
pub fn note_remove_image(app: AppHandle, id: i64, name: String) -> Result<(), String> {
    let path = image_path(&name)?;
    {
        let db = app.state::<Db>();
        let c = db.0.lock().unwrap();
        let list: Vec<String> = images_of(&c, id)?.into_iter().filter(|n| *n != name).collect();
        set_images(&c, id, &list)?;
    }
    let _ = std::fs::remove_file(path);
    changed(&app);
    Ok(())
}

#[tauri::command]
pub async fn note_image(name: String) -> Result<String, String> {
    let bytes = std::fs::read(image_path(&name)?).map_err(|e| e.to_string())?;
    let mime = if name.ends_with(".jpg") { "image/jpeg" } else { "image/png" };
    Ok(format!("data:{mime};base64,{}", base64::engine::general_purpose::STANDARD.encode(bytes)))
}

/// Native drag of the image file, so it can be dropped into Explorer, chat apps, etc.
#[tauri::command]
pub fn note_drag_image(window: WebviewWindow, name: String) -> Result<(), String> {
    let path = image_path(&name)?;
    drag::start_drag(&window, drag::DragItem::Files(vec![path.clone()]), drag::Image::File(path), |_, _| {}, Default::default())
        .map_err(|e| e.to_string())
}

/// Daily: trash expired notes, then delete long-trashed notes and their images.
pub fn housekeeping(app: &AppHandle) {
    let days = app.state::<crate::AppState>().config.lock().unwrap()
        .widget_settings("notes")["temporaryDays"].as_u64().map(|d| d as u32);
    let now = now_ms();
    {
        let db = app.state::<Db>();
        let c = db.0.lock().unwrap();
        let all: Vec<Note> = c.prepare(&format!("SELECT {COLS} FROM notes")).unwrap()
            .query_map([], row).map(|r| r.filter_map(Result::ok).collect()).unwrap_or_default();
        for n in all {
            match n.deleted_at {
                None if expired(now, n.updated_at, n.pinned, days) => {
                    let _ = c.execute("UPDATE notes SET deleted_at = ?2 WHERE id = ?1", params![n.id, now]);
                }
                Some(d) if purge_due(now, d) => {
                    for img in &n.images { if let Ok(p) = image_path(img) { let _ = std::fs::remove_file(p); } }
                    let _ = c.execute("DELETE FROM notes WHERE id = ?1", [n.id]);
                }
                _ => {}
            }
        }
    }
    changed(app);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pinned_never_expires() { assert!(!expired(100 * DAY, 0, true, Some(1))); }
    #[test]
    fn expires_after_days() {
        assert!(expired(8 * DAY, 0, false, Some(7)));
        assert!(!expired(6 * DAY, 0, false, Some(7)));
    }
    #[test]
    fn off_means_never() {
        assert!(!expired(999 * DAY, 0, false, None));
        assert!(!expired(999 * DAY, 0, false, Some(0)));
    }
    #[test]
    fn purge_after_7_days() {
        assert!(purge_due(8 * DAY, DAY));
        assert!(!purge_due(7 * DAY, DAY));
    }
    #[test]
    fn rejects_oversize_image() {
        let mut big = b"\x89PNG\r\n\x1a\n".to_vec();
        big.resize(MAX_IMAGE + 1, 0);
        assert!(check_image(&big).is_err());
    }
    #[test]
    fn rejects_non_image() {
        assert!(check_image(b"hello world").is_err());
        assert_eq!(check_image(b"\x89PNG\r\n\x1a\nrest").unwrap(), "png");
        assert_eq!(check_image(b"\xff\xd8\xff\xe0rest").unwrap(), "jpg");
    }
    #[test]
    fn rejects_path_traversal_name() {
        assert!(!safe_name("../config.json"));
        assert!(!safe_name(r"a\b.png"));
        assert!(!safe_name("a/b.png"));
        assert!(!safe_name(""));
        assert!(safe_name("12-1700000000000-3.png"));
    }
}
